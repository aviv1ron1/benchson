"""Generates per-tier lm-eval subtasks for the Benchson benchmark.

For each task family (create/fix/modify) and each difficulty tier / source present in
its test split, emits a tiny YAML that `include:`s the base family task and filters
the docs to that tier (via `utils.keep_<tier>`). Also writes a `benchson_tiers` group
that runs them all, so `lm_eval --tasks benchson_tiers` prints a per-tier breakdown
instead of one aggregate.

Run from the repo root:
    uv run python lm_eval_tasks/generate_tier_tasks.py
"""

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
TIERS_DIR = os.path.join(HERE, "tiers")
FAMILIES = {"create": "benchmark_create", "fix": "benchmark_fix", "modify": "benchmark_modify"}


def _tier(rec):
    return rec.get("subset") or rec.get("source")


def _fn_name(tier):
    import re
    return "keep_" + re.sub(r"[^a-z0-9]+", "_", str(tier).lower()).strip("_")


def _safe(tier):
    import re
    return re.sub(r"[^A-Za-z0-9]+", "_", str(tier)).strip("_")


def tiers_present(dataset):
    """Distinct tiers in a family's test split (so we never emit empty tasks)."""
    test_dir = os.path.join(os.getcwd(), "data", dataset, "test")
    seen = {}
    if not os.path.isdir(test_dir):
        return seen
    for fn in os.listdir(test_dir):
        if not fn.endswith(".json"):
            continue
        with open(os.path.join(test_dir, fn), "r", encoding="utf-8") as f:
            t = _tier(json.load(f))
        seen[t] = seen.get(t, 0) + 1
    return seen


def main():
    os.makedirs(TIERS_DIR, exist_ok=True)
    # clear stale generated files
    for fn in os.listdir(TIERS_DIR):
        if fn.endswith(".yaml"):
            os.remove(os.path.join(TIERS_DIR, fn))

    all_tasks = []
    for family, dataset in FAMILIES.items():
        present = tiers_present(dataset)
        for tier, n in sorted(present.items()):
            task_name = f"benchson_{family}_{_safe(tier)}"
            path = os.path.join(TIERS_DIR, task_name + ".yaml")
            with open(path, "w", encoding="utf-8") as f:
                f.write(
                    f"# {n} instances. Generated by generate_tier_tasks.py — do not edit by hand.\n"
                    f"include: ../benchson_{family}.yaml\n"
                    f"task: {task_name}\n"
                    f"process_docs: !function utils.{_fn_name(tier)}\n"
                )
            all_tasks.append(task_name)
            print(f"wrote {task_name} ({n} instances)")

    group_path = os.path.join(HERE, "benchson_tiers.yaml")
    with open(group_path, "w", encoding="utf-8") as f:
        f.write("# Generated by generate_tier_tasks.py — per-tier breakdown of every family.\n")
        f.write("group: benchson_tiers\ntask:\n")
        for t in all_tasks:
            f.write(f"  - {t}\n")
        f.write("metadata:\n  version: 1\n")
    print(f"wrote group benchson_tiers ({len(all_tasks)} tasks)")


if __name__ == "__main__":
    main()
